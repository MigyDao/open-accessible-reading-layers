// Compile in Node, never in the CSP-constrained desktop WebView.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const schema = JSON.parse(await readFile(new URL("../schema/orl-0.1.schema.json", import.meta.url), "utf8"));
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true } });
addFormats(ajv);
const validate = ajv.compile(schema);
const destination = new URL("../packages/orl-core/src/generated/", import.meta.url);
await mkdir(destination, { recursive: true });
await writeFile(new URL("orl-schema.cjs", destination),
  "// Generated by scripts/generate-orl-validator.mjs. Do not edit.\n" + standaloneCode(ajv, validate) + "\n");
